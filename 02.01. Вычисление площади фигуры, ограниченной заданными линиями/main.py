from math import cos, sin, log
from random import uniform
#-------------------------------------------------------------------------------


# функции, ограничивающие фигуру
def fun1(x):
    return cos(x) + sin(5 * x)

#-------------------------------------------------------------------------------

def fun2(x):
    return sin(x) + log(x)

#-------------------------------------------------------------------------------


# вычисление площади фигуры методом прямоугольников
def Rectangle_method(a, b, dx):
    S = 0                 
    x = a 
    while x <= b:
        y1 = fun1(x)              
        y2 = fun2(x)                 
        y = y2 - y1                          
        ds = y * dx                          
        S += ds
        x += dx

    return S

#-------------------------------------------------------------------------------


# вычисление площади фигуры методом трапеций
def Trapezoid_method(a, b, dx):
    S = 0           
    x = a

    while x <= b:
        y1 = fun1(x)              
        y2 = fun1(x + dx)  
        ds1 = (y1 + y2) / 2 * dx              

        y1 = fun2(x)                  
        y2 = fun2(x + dx)        
        ds2 = (y1 + y2) / 2 * dx              

        ds = ds2 - ds1                       

        S += ds
        x += dx

    return S

#-------------------------------------------------------------------------------


# вычисление площади фигуры методом Монте-Карло
def Monte_Carlo_method(a, b, N):
    x = a
    dx = 0.1
    
    min1 = fun1(x)
    max1 = fun2(x)
    
    steps = int((b - a) / dx) 
        
    for i in range(steps + 1):
        x = a + i * dx
            
        y1 = fun1(x)
        y2 = fun2(x)
    
        if y1 < min1:
            min1 = y1
        if y2 > max1:
            max1 = y2
                 
    n = 0                                              
    i = 0
        
    while i < N:                                        
        x = uniform(a, b)
        y = uniform(min1, max1)
            
        y1 = fun1(x)
        y2 = fun2(x)
            
        if y1 <= y <= y2:
             n += 1
                
        i += 1
                
    S0 = (b - a) * (max1 - min1)
    S1 = S0 * n / N

    return S1

#-------------------------------------------------------------------------------


while True:
    print('Для выбора метода интегрирования введите требуемое число:')
    print('1 - метод прямоугольников')
    print('2 - метод трапеций')

    choice = input()

    a = float(input('Введите нижний предел интегрирования a: '))
    b = float(input('Введите верхний предел интегрирования b: '))
    dx = float(input('Введите шаг интегрирования dx: '))

    N = int(input('Введите количество точек N: '))
    
    if choice == '1':                               # метод прямоугольников
        S = Rectangle_method(a, b, dx)
    elif choice == '2':                             # метод трапеций
        S = Trapezoid_method(a, b, dx)

    S1 = Monte_Carlo_method(a, b, N)                # метод Монте-Карло


    print('\nРезультат:\n')

    if choice == '1':
        print(f'Метод прямоугольников   {S:g} ед. кв.')
    if choice == '2':
        print(f'Метод трапеций          {S:g} ед. кв.')

    print(f'Метод Монте-Карло       {S1:g} ед. кв.')

    print('\n----------------------------------------\n')

