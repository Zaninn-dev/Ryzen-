from math import sin, cos, log
from random import uniform

import Dec as d
#-------------------------------------------------------------------------------


# функция, ограничивающая фигуру сверху
def fun1(x):
    return sin(x) + log(x)

#-------------------------------------------------------------------------------


# функция, ограничивающая фигуру снизу
def fun2(x):
    return cos(x) + sin(5 * x)

#-------------------------------------------------------------------------------


# метод прямоугольников
def Rectangle_method(a, b, dx):
    d.S = 0
    x = a
    while x < b:
        y1 = fun1(x)
        y2 = fun2(x)
        y = y1 - y2
        ds = y * dx
        d.S += ds

        x += dx

#-------------------------------------------------------------------------------


# метод трапеций
def Trapezoid_method(a, b, dx):
    d.S = 0
    x = a
    while x < b:
        y1 = fun2(x)
        y2 = fun2(x + dx)
        ds1 = (y1 + y2) / 2 * dx

        y3 = fun1(x)
        y4 = fun1(x + dx)
        ds2 = (y3 + y4) / 2 * dx

        ds = ds2 - ds1
        d.S += ds

        x += dx

#-------------------------------------------------------------------------------


# вычисление площади фигуры методом Монте-Карло
def Monte_Carlo_method(a, b, N):
    x = a
    dx = 0.001

    # нижняя граница — fun2, верхняя — fun1
    min1 = fun2(x)
    max1 = fun1(x)

    steps = int((b - a) / dx)

    for i in range(steps + 1):
        x = a + i * dx
        y1 = fun1(x)               # верхняя
        y2 = fun2(x)               # нижняя

        if y2 < min1:
            min1 = y2
        if y1 > max1:
            max1 = y1

    n = 0
    i = 0

    while i < N:
        x = uniform(a, b)
        y = uniform(min1, max1)

        y1 = fun1(x)               # верхняя
        y2 = fun2(x)               # нижняя

        if y2 <= y <= y1:         
            n += 1

        i += 1

    S0 = (b - a) * (max1 - min1)

    d.S_MK = S0 * n / N

