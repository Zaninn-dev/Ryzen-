
R1 = 1              # радиус внутренней окружности
R2 = 2 * R1         # радиус внешней окружности

while True:
    x = float(input('Введите координату x: '))
    y = float(input('Введите координату y: '))

    print('\nРезультат:\n')

    if x**2 + y**2 <= R1**2:
        print('Область попадания A')

    if (-R2 <= x <= 0 and 0 <= y <= R2 and  x**2 + y**2 <= R2**2 and x**2 + y**2 >= R1**2) or \
       (0 <= x <= R2 and -R2 <= y <= 0 and  x**2 + y**2 <= R2**2 and x**2 + y**2 >= R1**2):
        print('Область попадания B')

    if (-R2 <= x <= 0 and -R2 <= y <= 0 and x**2 + y**2 >= R1**2):
        print('Область попадания C')

    if (0 <= x <= R2 and 0 <= y <= R2 and x**2 + y**2 >= R1**2):
        print('Область попадания D')

    if (x <= -R2 or x >= R2 or y <= -R2 or y >= R2) or \
       (x <= 0 and y >= 0 or x >= 0 and y <= 0) and x**2 + y**2 >= R2**2:
        print('Область попадания E')

    print('\n----------------------------------------')




